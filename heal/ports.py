"""
The ports: what the agent needs from each kind of system. To support another tool
(GitLab CI, Azure DevOps, Flux, Dagster, ...) write a class with the same methods and
register it in heal/context.py. Nothing in the agent, the guard or the workflow changes.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol


@dataclass
class Incident:
    key: str              # stable id, e.g. "github:123456:1"; processed keys are never handled twice
    source: str           # deploy | github | jenkins | airflow
    ref: str              # run id / build number / revision / dag_run_id
    title: str
    evidence: str         # what the detector saw; the agent investigates further with tools
    url: str = ""
    facts: dict = field(default_factory=dict)


class CIProvider(Protocol):            # GitHub Actions (also: GitLab, CircleCI, Buildkite ...)
    def failed_runs(self, since_hours: int) -> list[dict]: ...
    def run(self, run_id: int) -> dict: ...
    def failed_jobs(self, run_id: int) -> list[dict]: ...
    def job_log(self, job_id: int) -> str: ...
    def commit(self, sha: str) -> dict: ...
    def rerun_failed_jobs(self, run_id: int) -> str: ...
    def wait_for_run(self, run_id: int, min_attempt: int, timeout: int) -> dict: ...


class BuildServer(Protocol):           # Jenkins (also: TeamCity, Bamboo ...)
    def failed_builds(self, since_hours: int) -> list[dict]: ...
    def build(self, number: int) -> dict: ...
    def console_tail(self, number: int) -> str: ...
    def rebuild(self, number: int) -> int: ...
    def wait_for_build(self, number: int, timeout: int) -> dict: ...


class Deployer(Protocol):              # Argo CD (also: Flux, Spinnaker, Helm ...)
    def app(self) -> dict: ...
    def rollback(self, history_id: int) -> str: ...
    def wait_settled(self, timeout: int) -> dict: ...


class Orchestrator(Protocol):          # Airflow (also: Dagster, Prefect ...)
    def failed_runs(self, since_hours: int) -> list[dict]: ...
    def run_state(self, dag_run_id: str) -> str: ...
    def failed_tasks(self, dag_run_id: str) -> list[dict]: ...
    def task_log(self, dag_run_id: str, task_id: str, try_number: int) -> str: ...
    def clear_failed(self, dag_run_id: str) -> str: ...
    def wait_for_run(self, dag_run_id: str, timeout: int) -> str: ...
